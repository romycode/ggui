// RenderInterface produces the source code (not formatted yet --
// format.Source happens in Emit, Task 10) of a .gen.go file for an
// interface. Tasks 8 and 9 extend it for requests and events; this task only
// covers the skeleton (struct, constructor, SetListener, descriptor, empty
// Dispatch) and enums.
func RenderInterface(iface resolve.ResolvedInterface) ([]byte, error) {
	var b bytes.Buffer

	fmt.Fprintf(&b, "// Code generated by waygenerator. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", iface.GoPackage)
	if iface.GoPackage == "wlcore" {
		fmt.Fprintf(&b, "import \"fmt\"\n\n")
	} else {
		// Every extension imports wlcore: that's where ProxyBase, Proxy,
		// Conn, Interface[T], Decoder, NewEncoder/NewProxyBase and DropFD
		// live -- the entire "Runtime contract" from waygenerator.md, not
		// just the symbols this particular interface touches. Every
		// generated file uses at least ProxyBase/Proxy/Conn (struct,
		// assertion, constructor), so the import is never unused.
		fmt.Fprintf(&b, "import (\n\t\"fmt\"\n\n\t%q\n)\n\n", wlcoreImportPath)
	}

	renderStructAndConstructor(&b, iface)
	renderListener(&b, iface)
	renderDescriptor(&b, iface)
	renderRequests(&b, iface)
	if err := renderDispatch(&b, iface); err != nil {
		return nil, err
	}
	renderEnums(&b, iface)
	renderOpcodeConsts(&b, iface)

	out := bytes.TrimRight(b.Bytes(), "\n")
	out = append(out, '\n')
	return out, nil
}

// wlcoreImportPath is the import path of the runtime package -- see
// "Runtime contract" in waygenerator.md.
const wlcoreImportPath = "github.com/romycode/ggui/wayland/wlcore"

// runtimeQual is the prefix that qualifies a runtime-contract symbol
// (ProxyBase, Proxy, Conn, Interface[T], Decoder, NewEncoder, NewProxyBase,
// DropFD) depending on the package being generated: empty within wlcore
// (which doesn't qualify itself, see "Naming conventions"), "wlcore." in
// any extension.
func runtimeQual(pkg string) string {
	if pkg == "wlcore" {
		return ""
	}
	return "wlcore."
}

// typeExpr computes the Go type expression of t as it must appear within
// package pkg. GoType.TypeString (computed in resolve, which doesn't know
// from which package it will be consumed) already carries the unqualified
// form; this is where it's decided whether a package prefix is needed, by
// comparing the referenced interface's package (ObjGoPackage, empty except
// for Object/NewIDStatic) against pkg. Two interfaces in different packages
// can share a GoType once the protocol prefix is stripped (wl_surface and
// xdg_surface are both "Surface"), so the prefix is necessary, not
// cosmetic.
func typeExpr(pkg string, t resolve.GoType) string {
	if t.ObjGoPackage != "" && t.ObjGoPackage != pkg {
		return "*" + t.ObjGoPackage + "." + t.ObjGoType
	}
	if t.Kind == resolve.KindFixed && pkg != "wlcore" {
		// Fixed isn't a reference to another interface (it doesn't carry
		// ObjGoPackage, see the GoType comment) -- it's a type of the
		// runtime contract itself, like ProxyBase/Proxy/Conn, so it's
		// qualified the same way: always wlcore.Fixed outside wlcore.
		return "wlcore.Fixed"
	}
	return t.TypeString
}

func renderRequests(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	pkg := iface.GoPackage
	q := runtimeQual(pkg)
	for _, r := range iface.Requests {
		switch {
		case r.BindLike:
			// bindRaw isn't exported -- it carries no doc comment, "go
			// doc" wouldn't show it and r.Summary/r.Doc (if the XML
			// provides them) would document a symbol that doesn't exist on
			// the public surface.
			fmt.Fprintf(b, "func (%s *%s) bindRaw(name uint32, iface string, version, newID uint32) error {\n", iface.Recv, iface.GoType)
			fmt.Fprintf(b, "\te := %sNewEncoder().Uint32(name).String(iface).Uint32(version).ID(newID)\n", q)
			fmt.Fprintf(b, "\treturn %s.Conn().Send(%s.ID(), opReq%s%s, e)\n}\n\n", iface.Recv, iface.Recv, iface.GoType, r.GoName)
		case r.Destructor:
			renderDocComment(b, "", r.GoName, r.Summary, r.Doc, docParamsFor(r.Args))
			fmt.Fprintf(b, "func (%s *%s) %s() error {\n", iface.Recv, iface.GoType, r.GoName)
			renderVersionGuard(b, iface, r, false)
			fmt.Fprintf(b, "\terr := %s.Conn().Send(%s.ID(), opReq%s%s, %sNewEncoder())\n", iface.Recv, iface.Recv, iface.GoType, r.GoName, q)
			fmt.Fprintf(b, "\t%s.Conn().Destroy(%s)\n\treturn err\n}\n\n", iface.Recv, iface.Recv)
		case r.Returns != nil:
			renderDocComment(b, "", r.GoName, r.Summary, r.Doc, docParamsFor(r.Args))
			fmt.Fprintf(b, "func (%s *%s) %s(%s) (%s, error) {\n", iface.Recv, iface.GoType, r.GoName, paramList(pkg, r.Args), typeExpr(pkg, *r.Returns))
			renderVersionGuard(b, iface, r, true)
			fmt.Fprintf(b, "\tid := %s.Conn().NewID()\n", iface.Recv)
			// new<Type>FromProxyBase isn't qualified: a request's new_id
			// always constructs an object of its own package (see
			// checkDAG in resolve.go -- no interface across the current 5
			// phases of wlcore.xml has a new_id-return crossing packages),
			// and even if it did, that function isn't exported -- there
			// would be no way to call it from outside.
			fmt.Fprintf(b, "\tx := new%sFromProxyBase(%sNewProxyBase(id, %s.Version(), %s.Conn()))\n", r.Returns.ObjGoType, q, iface.Recv, iface.Recv)
			fmt.Fprintf(b, "\t%s.Conn().Register(x)\n\n", iface.Recv)
			renderNullableObjectIDs(b, r.Args)
			fmt.Fprintf(b, "\te := %s\n", encoderChain(pkg, append([]resolve.ResolvedArg{{GoName: "id", Type: resolve.GoType{Kind: resolve.KindObject}}}, r.Args...), true))
			fmt.Fprintf(b, "\tif err := %s.Conn().Send(%s.ID(), opReq%s%s, e%s); err != nil {\n\t\treturn nil, err\n\t}\n", iface.Recv, iface.Recv, iface.GoType, r.GoName, fdVariadic(r.Args))
			fmt.Fprintf(b, "\treturn x, nil\n}\n\n")
		default:
			renderDocComment(b, "", r.GoName, r.Summary, r.Doc, docParamsFor(r.Args))
			fmt.Fprintf(b, "func (%s *%s) %s(%s) error {\n", iface.Recv, iface.GoType, r.GoName, paramList(pkg, r.Args))
			renderVersionGuard(b, iface, r, false)
			renderNullableObjectIDs(b, r.Args)
			fmt.Fprintf(b, "\te := %s\n", encoderChain(pkg, r.Args, false))
			fmt.Fprintf(b, "\treturn %s.Conn().Send(%s.ID(), opReq%s%s, e%s)\n}\n\n", iface.Recv, iface.Recv, iface.GoType, r.GoName, fdVariadic(r.Args))
		}
	}
}

// docParam is a (name, summary) pair from an <arg>, for the "Parameters:"
// list that renderDocComment appends below the main comment.
type docParam struct {
	name    string
	summary string
}

func docParamsFor(args []resolve.ResolvedArg) []docParam {
	params := make([]docParam, len(args))
	for i, a := range args {
		params[i] = docParam{name: a.GoName, summary: a.Summary}
	}
	return params
}

// renderDocComment emits the doc comment for a symbol generated from a
// <description>: the first line starts with the Go symbol's own name, as
// mandated by docs/waygenerator.md ("Pass 3 -- emit", "<description> ->
// doc comments, starting with the Go symbol's name so go doc shows them
// properly"). Emits nothing if there's no summary -- not every
// <description> carries one, and an empty comment ("// Foo:" and nothing
// else) would be worse than none. indent is the tab prefix for the
// position where it's emitted (empty at file level, "\t" inside a
// struct).
func renderDocComment(b *bytes.Buffer, indent, symbol, summary, body string, params []docParam) {
	if summary == "" {
		return
	}
	fmt.Fprintf(b, "%s// %s: %s\n", indent, symbol, summary)
	if lines := docBodyLines(body); len(lines) > 0 {
		fmt.Fprintf(b, "%s//\n", indent)
		for _, l := range lines {
			if l == "" {
				fmt.Fprintf(b, "%s//\n", indent)
			} else {
				fmt.Fprintf(b, "%s// %s\n", indent, l)
			}
		}
	}
	var withSummary []docParam
	for _, p := range params {
		if p.summary != "" {
			withSummary = append(withSummary, p)
		}
	}
	if len(withSummary) > 0 {
		fmt.Fprintf(b, "%s//\n", indent)
		fmt.Fprintf(b, "%s// Parameters:\n", indent)
		for _, p := range withSummary {
			fmt.Fprintf(b, "%s//   - %s: %s\n", indent, p.name, p.summary)
		}
	}
}

// docBodyLines cleans up the raw indentation of a <description>'s body:
// each line arrives exactly as it was in the XML (indented), and the first
// and last are usually blank (the body starts right after the opening
// '>'). Trims each line and drops the blank ones at both ends, keeping the
// ones in between as a paragraph separator.
func docBodyLines(body string) []string {
	raw := strings.Split(body, "\n")
	lines := make([]string, 0, len(raw))
	for _, l := range raw {
		lines = append(lines, strings.TrimSpace(l))
	}
	for len(lines) > 0 && lines[0] == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

func renderNullableObjectIDs(b *bytes.Buffer, args []resolve.ResolvedArg) {
	for _, a := range args {
		if a.Type.Kind != resolve.KindObject || !a.Type.AllowNull {
			continue
		}
		fmt.Fprintf(b, "\tvar %sID uint32\n", a.GoName)
		fmt.Fprintf(b, "\tif %s != nil {\n", a.GoName)
		fmt.Fprintf(b, "\t\t%sID = %s.ID()\n", a.GoName, a.GoName)
		fmt.Fprintf(b, "\t}\n")
	}
}

func renderVersionGuard(b *bytes.Buffer, iface resolve.ResolvedInterface, r resolve.ResolvedRequest, returnsObj bool) {
	if r.Since <= 1 {
		return
	}
	fmt.Fprintf(b, "\tif %s.Version() < %d {\n", iface.Recv, r.Since)
	if returnsObj {
		fmt.Fprintf(b, "\t\treturn nil, fmt.Errorf(\"%s: %s requires version >= %d, got %%d\", %s.Version())\n", iface.GoPackage, r.XMLName, r.Since, iface.Recv)
	} else {
		fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"%s: %s requires version >= %d, got %%d\", %s.Version())\n", iface.GoPackage, r.XMLName, r.Since, iface.Recv)
	}
	fmt.Fprintf(b, "\t}\n")
}

// paramList builds the parameter list of a request method, in XML order,
// skipping the new_id (it never arrives here as an Arg, see
// resolve.resolveRequest) but including the fds in their natural
// position.
func paramList(pkg string, args []resolve.ResolvedArg) string {
	var parts []string
	for _, a := range args {
		parts = append(parts, a.GoName+" "+typeExpr(pkg, a.Type))
	}
	return joinComma(parts)
}

// encoderChain builds the NewEncoder()....... chain, skipping fd args (they
// go to Send as a variadic, not to the Encoder). withLeadingID prepends
// ".ID(id)" for the static new_id case, where the first element of args is
// already that synthetic id (see the call in renderRequests that passes it
// an extra arg with GoName "id").
func encoderChain(pkg string, args []resolve.ResolvedArg, withLeadingID bool) string {
	chain := runtimeQual(pkg) + "NewEncoder()"
	for i, a := range args {
		if withLeadingID && i == 0 {
			chain += ".ID(id)"
			continue
		}
		if a.IsFD {
			continue
		}
		switch a.Type.TypeString {
		case "int32":
			chain += ".Int32(" + a.GoName + ")"
		case "uint32":
			chain += ".Uint32(" + a.GoName + ")"
		case "Fixed":
			chain += ".Fixed(" + a.GoName + ")"
		case "string":
			chain += ".String(" + a.GoName + ")"
		case "*string":
			chain += ".StringOpt(" + a.GoName + ")"
		case "[]byte":
			chain += ".Array(" + a.GoName + ")"
		default:
			switch a.Type.Kind {
			case resolve.KindEnum:
				chain += ".Uint32(uint32(" + a.GoName + "))"
			case resolve.KindObject:
				if a.Type.AllowNull {
					chain += ".ID(" + a.GoName + "ID)"
				} else {
					chain += ".ID(" + a.GoName + ".ID())"
				}
			case resolve.KindObjectDyn:
				chain += ".Uint32(" + a.GoName + ")"
			}
		}
	}
	return chain
}

// fdVariadic builds ", fd1, fd2" for a request's fd args, in their XML
// order -- they all go at the end as Send's variadic.
func fdVariadic(args []resolve.ResolvedArg) string {
	var s string
	for _, a := range args {
		if a.IsFD {
			s += ", " + a.GoName
		}
	}
	return s
}

func joinComma(parts []string) string {
	s := ""
	for i, p := range parts {
		if i > 0 {
			s += ", "
		}
		s += p
	}
	return s
}

func renderOpcodeConsts(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	if len(iface.Requests) == 0 && len(iface.Events) == 0 {
		return
	}
	fmt.Fprintf(b, "const (\n")
	for _, r := range iface.Requests {
		fmt.Fprintf(b, "\topReq%s%s = %d\n", iface.GoType, r.GoName, reqOpcode(iface, r.XMLName))
	}
	for _, ev := range iface.Events {
		fmt.Fprintf(b, "\topEvt%s%s = %d\n", iface.GoType, ev.GoName, evtOpcode(iface, ev.XMLName))
	}
	fmt.Fprintf(b, ")\n\n")
}

func reqOpcode(iface resolve.ResolvedInterface, xmlName string) int {
	for i, r := range iface.Requests {
		if r.XMLName == xmlName {
			return i
		}
	}
	return -1
}

func evtOpcode(iface resolve.ResolvedInterface, xmlName string) int {
	for i, ev := range iface.Events {
		if ev.XMLName == xmlName {
			return i
		}
	}
	return -1
}

func renderStructAndConstructor(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	q := runtimeQual(iface.GoPackage)
	renderDocComment(b, "", iface.GoType, iface.Summary, iface.Doc, nil)
	fmt.Fprintf(b, "type %s struct {\n\t%sProxyBase\n\tlistener %sListener\n}\n\n", iface.GoType, q, iface.GoType)
	fmt.Fprintf(b, "var _ %sProxy = (*%s)(nil)\n\n", q, iface.GoType)
	// The parameter is named "conn", not "c": if iface.Recv were also "c"
	// (Callback, Compositor -- any interface whose GoType starts with
	// 'C'), "c := &Foo{...}" with a parameter "c *Conn" would be an
	// invalid redeclaration ("no new variables on left side of :="). A
	// parameter name that can never match a single-letter receiver avoids
	// the collision for any interface, not just today's.
	fmt.Fprintf(b, "func new%s(id, version uint32, conn *%sConn) *%s {\n", iface.GoType, q, iface.GoType)
	fmt.Fprintf(b, "\treturn new%sFromProxyBase(%sNewProxyBase(id, version, conn))\n}\n\n", iface.GoType, q)
	fmt.Fprintf(b, "func new%sFromProxyBase(base %sProxyBase) *%s {\n", iface.GoType, q, iface.GoType)
	fmt.Fprintf(b, "\t%s := &%s{ProxyBase: base}\n", iface.Recv, iface.GoType)
	if iface.HasEvents {
		fmt.Fprintf(b, "\t%s.OnClear = func() { %s.listener = %sListener{} }\n", iface.Recv, iface.Recv, iface.GoType)
	}
	fmt.Fprintf(b, "\treturn %s\n}\n\n", iface.Recv)
	if iface.PublicListener {
		fmt.Fprintf(b, "func (%s *%s) SetListener(l %sListener) { %s.listener = l }\n\n", iface.Recv, iface.GoType, iface.GoType, iface.Recv)
	}
}

func renderListener(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	fmt.Fprintf(b, "type %sListener struct {\n", iface.GoType)
	for _, ev := range iface.Events {
		renderDocComment(b, "\t", ev.GoName, ev.Summary, ev.Doc, docParamsFor(ev.Args))
		fmt.Fprintf(b, "\t%s func(%s)\n", ev.GoName, paramList(iface.GoPackage, ev.Args))
	}
	fmt.Fprintf(b, "}\n\n")
}

func renderDescriptor(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	fmt.Fprintf(b, "var %sInterface = %sInterface[*%s]{\n", iface.GoType, runtimeQual(iface.GoPackage), iface.GoType)
	fmt.Fprintf(b, "\tName:       %q,\n", iface.XMLName)
	fmt.Fprintf(b, "\tMaxVersion: %d,\n", iface.MaxVersion)
	fmt.Fprintf(b, "\tNew:        new%sFromProxyBase,\n", iface.GoType)
	fmt.Fprintf(b, "}\n\n")
}

func renderDispatch(b *bytes.Buffer, iface resolve.ResolvedInterface) error {
	// The parameter is named "dec", not "d": if iface.Recv were also "d"
	// (Display, DataDevice, DataDeviceManager, DataOffer, DataSource --
	// any interface whose GoType starts with 'D'), "d *Decoder" would
	// collide with the receiver ("d redeclared in this block").
	fmt.Fprintf(b, "func (%s *%s) Dispatch(opcode uint16, dec *%sDecoder) error {\n", iface.Recv, iface.GoType, runtimeQual(iface.GoPackage))
	fmt.Fprintf(b, "\tswitch opcode {\n")
	for _, ev := range iface.Events {
		renderEventCase(b, iface, ev)
	}
	fmt.Fprintf(b, "\tdefault:\n\t\treturn fmt.Errorf(\"%s: unknown opcode %%d in %s\", opcode)\n", iface.GoPackage, iface.XMLName)
	fmt.Fprintf(b, "\t}\n")
	if len(iface.Events) > 0 {
		// With at least one event, the cases (which don't return -- see
		// renderEventCase) fall through to the end of the switch, so an
		// explicit return is needed. With zero events the switch only has
		// the default, which does end in a return: Go already treats it
		// as a "terminating statement" (spec, "Terminating statements"),
		// so a "return nil" after it would be dead code -- "go vet" flags
		// it as unreachable in the 8 wayland.xml interfaces with no
		// events (wl_compositor, wl_region, ...).
		fmt.Fprintf(b, "\treturn nil\n")
	}
	fmt.Fprintf(b, "}\n\n")
	return nil
}

func renderEventCase(b *bytes.Buffer, iface resolve.ResolvedInterface, ev resolve.ResolvedEvent) {
	q := runtimeQual(iface.GoPackage)
	fmt.Fprintf(b, "\tcase opEvt%s%s:\n", iface.GoType, ev.GoName)
	for _, a := range ev.Args {
		renderEventArgDecode(b, iface, a)
	}
	if ev.FDOwning {
		// ev.Destructor isn't handled here even though it could be in
		// principle (no real wayland.xml event combines type="destructor"
		// with an fd arg): the fd travels attached to an object that the
		// event itself just destroyed, a combination the Wayland protocol
		// doesn't use and that adding without a real fixture to exercise
		// it would be dead code.
		fmt.Fprintf(b, "\t\tif err := dec.Err(); err != nil {\n")
		for _, a := range ev.Args {
			if a.IsFD {
				fmt.Fprintf(b, "\t\t\t%sDropFD(%s)\n", q, a.GoName)
			}
		}
		fmt.Fprintf(b, "\t\t\treturn err\n\t\t}\n")
		fmt.Fprintf(b, "\t\tif %s.listener.%s == nil {\n", iface.Recv, ev.GoName)
		for _, a := range ev.Args {
			if a.IsFD {
				fmt.Fprintf(b, "\t\t\t%sDropFD(%s)\n", q, a.GoName)
			}
		}
		fmt.Fprintf(b, "\t\t\tbreak\n\t\t}\n")
		fmt.Fprintf(b, "\t\t%s.listener.%s(%s)\n", iface.Recv, ev.GoName, argNameList(ev.Args))
		return
	}
	fmt.Fprintf(b, "\t\tif err := dec.Err(); err != nil {\n\t\t\treturn err\n\t\t}\n")
	for _, a := range ev.Args {
		if a.Type.Kind == resolve.KindNewIDStatic {
			// new<Type>FromProxyBase isn't qualified -- same reasoning as
			// in renderRequests: it always constructs an object of its own
			// package, and it isn't exported.
			fmt.Fprintf(b, "\t\t%s := new%sFromProxyBase(%sNewProxyBase(%sID, %s.Version(), %s.Conn()))\n", a.GoName, a.Type.ObjGoType, q, a.GoName, iface.Recv, iface.Recv)
			fmt.Fprintf(b, "\t\t%s.Conn().Register(%s)\n", iface.Recv, a.GoName)
		} else if a.Type.Kind == resolve.KindObject {
			fmt.Fprintf(b, "\t\t%s, _ := %s.Conn().Lookup(%sID).(%s)\n", a.GoName, iface.Recv, a.GoName, typeExpr(iface.GoPackage, a.Type))
		}
	}
	fmt.Fprintf(b, "\t\tif %s.listener.%s != nil {\n", iface.Recv, ev.GoName)
	fmt.Fprintf(b, "\t\t\t%s.listener.%s(%s)\n\t\t}\n", iface.Recv, ev.GoName, argNameList(ev.Args))
	if ev.Destructor {
		// A destructor event (wl_callback.done is the only case today)
		// destroys the proxy whether or not there was a listener -- that's
		// why this call lives outside the if above, same as the destructor
		// request (case r.Destructor) already does with
		// c.Conn().Destroy(c).
		fmt.Fprintf(b, "\t\t%s.Conn().Destroy(%s)\n", iface.Recv, iface.Recv)
	}
}

func renderEventArgDecode(b *bytes.Buffer, iface resolve.ResolvedInterface, a resolve.ResolvedArg) {
	switch {
	case a.IsFD:
		fmt.Fprintf(b, "\t\t%s := dec.FD()\n", a.GoName)
	case a.Type.Kind == resolve.KindNewIDStatic || a.Type.Kind == resolve.KindObject:
		fmt.Fprintf(b, "\t\t%sID := dec.ID()\n", a.GoName)
	default:
		fmt.Fprintf(b, "\t\t%s := %s\n", a.GoName, decodeExpr(a))
	}
}

func decodeExpr(a resolve.ResolvedArg) string {
	switch a.Type.Kind {
	case resolve.KindFixed:
		return "dec.Fixed()"
	case resolve.KindEnum:
		return a.Type.TypeString + "(dec.Uint32())"
	case resolve.KindObject:
		return "dec.ID()" // Dispatch still has to resolve it with Lookup -- see note below
	case resolve.KindObjectDyn:
		return "dec.Uint32()"
	}
	switch a.Type.TypeString {
	case "int32":
		return "dec.Int32()"
	case "uint32":
		return "dec.Uint32()"
	case "string":
		return "dec.String()"
	case "*string":
		return "dec.StringOpt()"
	case "[]byte":
		return "dec.Array()"
	}
	return "dec.Uint32()"
}

func argNameList(args []resolve.ResolvedArg) string {
	var parts []string
	for _, a := range args {
		parts = append(parts, a.GoName)
	}
	return joinComma(parts)
}

func renderEnums(b *bytes.Buffer, iface resolve.ResolvedInterface) {
	for _, en := range iface.Enums {
		renderDocComment(b, "", en.GoName, en.Summary, en.Doc, nil)
		fmt.Fprintf(b, "type %s uint32\n\n", en.GoName)
		fmt.Fprintf(b, "const (\n")
		for _, e := range en.Entries {
			if e.Summary != "" {
				fmt.Fprintf(b, "\t%s %s = %s // %s\n", e.GoName, en.GoName, e.Value, e.Summary)
			} else {
				fmt.Fprintf(b, "\t%s %s = %s\n", e.GoName, en.GoName, e.Value)
			}
		}
		fmt.Fprintf(b, ")\n\n")
		if en.Bitfield {
			fmt.Fprintf(b, "func (v %s) Has(flag %s) bool { return v&flag != 0 }\n\n", en.GoName, en.GoName)
		}
	}
}

// Emit renders and writes one .gen.go per interface to outDir. Writes
// nothing if any interface fails to render or format -- all or nothing, so
// as not to leave a half-done regeneration mixed with files from a
// previous run that did generate correctly.
func Emit(m resolve.Model, outDir string) error {
	ifaces := append([]resolve.ResolvedInterface(nil), m.Interfaces...)
	sort.Slice(ifaces, func(i, j int) bool { return ifaces[i].XMLName < ifaces[j].XMLName })

	type file struct {
		dir  string
		name string
		data []byte
	}
	var files []file
	for _, iface := range ifaces {
		src, err := RenderInterface(iface)
		if err != nil {
			return fmt.Errorf("codegen: rendering %s: %w", iface.XMLName, err)
		}
		formatted, err := format.Source(src)
		if err != nil {
			return fmt.Errorf("codegen: %s produced invalid Go: %w", iface.XMLName, err)
		}
		files = append(files, file{dir: packageDir(outDir, iface.GoPackage), name: fileName(iface), data: formatted})
	}

	for _, f := range files {
		if err := os.MkdirAll(f.dir, 0o755); err != nil {
			return fmt.Errorf("codegen: creating %s: %w", f.dir, err)
		}
		path := filepath.Join(f.dir, f.name)
		if err := os.WriteFile(path, f.data, 0o644); err != nil {
			return fmt.Errorf("codegen: writing %s: %w", path, err)
		}
	}
	return nil
}

// packageDir resolves a package's output directory. outDir is wlcore's
// directory (wayland/wlcore, for compat with the current layout); wlcore is
// written there as-is. Any other package is a sibling directory,
// wayland/<package>, derived by substituting outDir's last segment -- so
// xdgshell, viewporter, fractionalscale and tablet land next to wlcore
// without main.go having to enumerate packages.
func packageDir(outDir, pkg string) string {
	if pkg == "wlcore" {
		return outDir
	}
	return filepath.Join(filepath.Dir(outDir), pkg)
}

// fileName derives the file name from the GoType, not the XMLName --
// snake_case of the Go type, not the XML name with its protocol prefix.
// wl_shm_pool -> ShmPool -> shm_pool.gen.go.
func fileName(iface resolve.ResolvedInterface) string {
	return pascalToSnake(iface.GoType) + ".gen.go"
}

func pascalToSnake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		b.WriteRune(r)
	}
	return strings.ToLower(b.String())
}
