package keysymdata

import (
	"bytes"
	"strings"
	"testing"
)

func TestRenderDeterministicGo(t *testing.T) {
	tables := Tables{
		Names:          map[string]uint32{"F2": 0xffbf, "F1": 0xffbe},
		CanonicalNames: map[uint32]string{0xffbf: "F2", 0xffbe: "F1"},
		Runes:          map[uint32]rune{0x03bc: '\u0167', 0xff8d: '\r'},
	}
	want := `// Code generated by keysymgen. DO NOT EDIT.

package keyboard

var keysymNames = map[string]Keysym{
	"F1": 0xffbe,
	"F2": 0xffbf,
}

var keysymCanonicalNames = map[Keysym]string{
	0xffbe: "F1",
	0xffbf: "F2",
}

var legacyRunes = map[Keysym]rune{
	0x03bc: 0x0167,
	0xff8d: 0x000d,
}
`
	got, err := Render(tables)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if string(got) != want {
		t.Fatalf("Render mismatch:\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
	again, err := Render(tables)
	if err != nil || !bytes.Equal(got, again) {
		t.Fatalf("second Render = %q, %v; want identical output", again, err)
	}
}

func TestGenerateBuildsAllTables(t *testing.T) {
	got, err := Generate(strings.NewReader(sampleHeader))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	for _, declaration := range []string{
		"var keysymNames = map[string]Keysym{",
		"var keysymCanonicalNames = map[Keysym]string{",
		"var legacyRunes = map[Keysym]rune{",
	} {
		if !bytes.Contains(got, []byte(declaration)) {
			t.Errorf("Generate(sampleHeader) missing %q", declaration)
		}
	}
}

func TestGeneratePropagatesParseError(t *testing.T) {
	_, err := Generate(strings.NewReader("#define XKB_KEY_Bad 0xnope\n"))
	if err == nil {
		t.Fatal("Generate(malformed header) succeeded")
	}
}
