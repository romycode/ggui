package keysymdata

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

func TestEmitWritesFormattedGeneratedFile(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "keysyms.h")
	out := filepath.Join(dir, "keysyms.gen.go")
	if err := os.WriteFile(in, []byte(sampleHeader), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Emit(in, out); err != nil {
		t.Fatalf("Emit: %v", err)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(data, []byte("// Code generated by keysymgen. DO NOT EDIT.\n")) {
		t.Fatalf("missing generated header: %s", data)
	}
}

func TestEmitLeavesExistingOutputOnParseFailure(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "bad.h")
	out := filepath.Join(dir, "keysyms.gen.go")
	if err := os.WriteFile(in, []byte("#define XKB_KEY_Bad 0xnope\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(out, []byte("keep me\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Emit(in, out); err == nil {
		t.Fatal("Emit succeeded with malformed input")
	}
	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != "keep me\n" {
		t.Fatalf("output changed after failure: %q", data)
	}
}
